library ieee;
use ieee.std_logic_1164.all;

package font_pkg is
  -- Original 5x7 uppercase bitmap font; one blank column is supplied by layout.
  function font_pixel(c : character; x, y : natural) return boolean;
end;
package body font_pkg is
  function font_pixel(c : character; x, y : natural) return boolean is
    variable bits : std_logic_vector(34 downto 0);
  begin
    case c is
      when 'A' => bits := "01110" & "10001" & "10001" & "11111" & "10001" & "10001" & "10001";
      when 'B' => bits := "11110" & "10001" & "10001" & "11110" & "10001" & "10001" & "11110";
      when 'C' => bits := "01111" & "10000" & "10000" & "10000" & "10000" & "10000" & "01111";
      when 'D' => bits := "11110" & "10001" & "10001" & "10001" & "10001" & "10001" & "11110";
      when 'E' => bits := "11111" & "10000" & "10000" & "11110" & "10000" & "10000" & "11111";
      when 'F' => bits := "11111" & "10000" & "10000" & "11110" & "10000" & "10000" & "10000";
      when 'G' => bits := "01111" & "10000" & "10000" & "10111" & "10001" & "10001" & "01111";
      when 'H' => bits := "10001" & "10001" & "10001" & "11111" & "10001" & "10001" & "10001";
      when 'I' => bits := "11111" & "00100" & "00100" & "00100" & "00100" & "00100" & "11111";
      when 'J' => bits := "00111" & "00010" & "00010" & "00010" & "10010" & "10010" & "01100";
      when 'K' => bits := "10001" & "10010" & "10100" & "11000" & "10100" & "10010" & "10001";
      when 'L' => bits := "10000" & "10000" & "10000" & "10000" & "10000" & "10000" & "11111";
      when 'M' => bits := "10001" & "11011" & "10101" & "10101" & "10001" & "10001" & "10001";
      when 'N' => bits := "10001" & "11001" & "10101" & "10011" & "10001" & "10001" & "10001";
      when 'O' => bits := "01110" & "10001" & "10001" & "10001" & "10001" & "10001" & "01110";
      when 'P' => bits := "11110" & "10001" & "10001" & "11110" & "10000" & "10000" & "10000";
      when 'Q' => bits := "01110" & "10001" & "10001" & "10001" & "10101" & "10010" & "01101";
      when 'R' => bits := "11110" & "10001" & "10001" & "11110" & "10100" & "10010" & "10001";
      when 'S' => bits := "01111" & "10000" & "10000" & "01110" & "00001" & "00001" & "11110";
      when 'T' => bits := "11111" & "00100" & "00100" & "00100" & "00100" & "00100" & "00100";
      when 'U' => bits := "10001" & "10001" & "10001" & "10001" & "10001" & "10001" & "01110";
      when 'V' => bits := "10001" & "10001" & "10001" & "10001" & "10001" & "01010" & "00100";
      when 'W' => bits := "10001" & "10001" & "10001" & "10101" & "10101" & "10101" & "01010";
      when 'X' => bits := "10001" & "10001" & "01010" & "00100" & "01010" & "10001" & "10001";
      when 'Y' => bits := "10001" & "10001" & "01010" & "00100" & "00100" & "00100" & "00100";
      when 'Z' => bits := "11111" & "00001" & "00010" & "00100" & "01000" & "10000" & "11111";
      when '0' => bits := "01110" & "10001" & "10011" & "10101" & "11001" & "10001" & "01110";
      when '1' => bits := "00100" & "01100" & "00100" & "00100" & "00100" & "00100" & "01110";
      when '2' => bits := "01110" & "10001" & "00001" & "00010" & "00100" & "01000" & "11111";
      when '3' => bits := "11110" & "00001" & "00001" & "01110" & "00001" & "00001" & "11110";
      when '4' => bits := "00010" & "00110" & "01010" & "10010" & "11111" & "00010" & "00010";
      when '5' => bits := "11111" & "10000" & "10000" & "11110" & "00001" & "00001" & "11110";
      when '6' => bits := "01110" & "10000" & "10000" & "11110" & "10001" & "10001" & "01110";
      when '7' => bits := "11111" & "00001" & "00010" & "00100" & "01000" & "01000" & "01000";
      when '8' => bits := "01110" & "10001" & "10001" & "01110" & "10001" & "10001" & "01110";
      when '9' => bits := "01110" & "10001" & "10001" & "01111" & "00001" & "00001" & "01110";
      when ':' => bits := "00000" & "00100" & "00100" & "00000" & "00100" & "00100" & "00000";
      when '?' => bits := "01110" & "10001" & "00001" & "00010" & "00100" & "00000" & "00100";
      when '-' => bits := "00000" & "00000" & "00000" & "11111" & "00000" & "00000" & "00000";
      when others => bits := (others => '0');
    end case;
    if x < 5 and y < 7 then return bits(34-y*5-x) = '1'; end if;
    return false;
  end;
end;
